import { readFile } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import { beginDish, cook, createPlayer, dialog, saved } from './helpers'

test('首发流程、三道菜、结算、刷新、导出导入与安全清档',async({page},info)=>{
  const problems: string[]=[]
  page.on('pageerror',error=>problems.push(error.message))
  page.on('response',res=>{ if(res.status()>=400)problems.push(res.url()+' '+res.status()) })
  await page.goto('./')
  await expect(page).toHaveTitle('龙潭商业街')
  await expect.poll(()=>page.locator('.title-art').evaluate((e:HTMLImageElement)=>e.complete&&e.naturalWidth>0)).toBe(true)
  await page.screenshot({path:info.outputPath('title.png')})
  await createPlayer(page)
  const first=await saved(page)
  expect(first.character).toEqual({name:'小岚',gender:1,hair:2,hairColor:1,skin:1,outfit:2})
  await page.screenshot({path:info.outputPath('street.png')})
  for (const name of ['龙潭鲜果茶摊','龙潭铁板炒饭']) {
    await page.getByRole('button',{name,exact:true}).click()
    await expect(dialog(page)).toContainText('开业条件预览')
    await page.keyboard.press('Escape')
  }
  await page.keyboard.down('ArrowLeft')
  await page.waitForTimeout(490)
  await page.keyboard.up('ArrowLeft')
  await expect.poll(async()=>(await saved(page)).position.x).toBeLessThan(414)
  await page.keyboard.down('ArrowDown')
  await page.waitForTimeout(360)
  await page.keyboard.up('ArrowDown')
  await expect.poll(async()=>(await saved(page)).position.y).toBeGreaterThan(311)
  await expect(page.getByRole('button',{name:'互动 · 龙潭炸香摊'})).toBeVisible()
  await page.keyboard.press('KeyE')
  await expect(dialog(page).getByRole('heading',{name:'龙潭炸香摊'})).toBeVisible()
  await beginDish(page,'金黄炸土豆')
  await dialog(page).getByRole('button',{name:'洗净土豆'}).click()
  const inProgress=await saved(page)
  expect(inProgress.cooking?.step).toBe(1)
  expect(inProgress.inventory.potato).toBe(3)
  await page.reload()
  await page.getByRole('button',{name:'继续游戏'}).click()
  await page.getByRole('navigation').getByRole('button',{name:'炸香摊'}).click()
  await expect(dialog(page).getByRole('button',{name:'削掉外皮'})).toBeVisible()
  await page.screenshot({path:info.outputPath('kitchen.png')})
  await cook(page,'金黄炸土豆')
  await beginDish(page,'香酥炸豆腐')
  await cook(page,'香酥炸豆腐')
  await beginDish(page,'桂阳风味油炸肉丸')
  await cook(page,'桂阳风味油炸肉丸')
  const beforeBuy=await saved(page)
  expect(beforeBuy.coins).toBe(156)
  expect(beforeBuy.popularity).toBe(9)
  expect(beforeBuy.xp).toBe(36)
  expect(beforeBuy.inventory).toEqual({potato:3,chili:4,cumin:4,salt:5,pork:3,seasoning:5,scallion:6,tofu:3,sauce:4})
  await dialog(page).getByRole('button',{name:'采购食材'}).click()
  await dialog(page).getByRole('listitem').filter({hasText:'黄心土豆'}).getByRole('button',{name:/购买/}).click()
  const afterBuy=await saved(page)
  expect(afterBuy.inventory.potato).toBe(6)
  expect(afterBuy.coins).toBe(148)
  await dialog(page).getByRole('button',{name:'回炸香摊'}).click()
  await dialog(page).getByRole('button',{name:'设备升级'}).click()
  await dialog(page).getByRole('button',{name:'购买升级'}).first().click()
  expect((await saved(page)).equipment).toBe(1)
  await dialog(page).getByRole('button',{name:'回炸香摊'}).click()
  await dialog(page).getByRole('button',{name:'收摊结算'}).click()
  await expect(dialog(page)).toContainText('+28 金币')
  const settled=await saved(page)
  expect(settled.summary?.orders).toBe(3)
  expect(settled.coins).toBe(121)
  await dialog(page).getByRole('button',{name:'开始下一天'}).click()
  await page.keyboard.press('Escape')
  await page.getByRole('button',{name:'设置',exact:true}).click()
  const downloadPromise=page.waitForEvent('download')
  await dialog(page).getByRole('button',{name:'导出存档'}).click()
  const download=await downloadPromise
  const data=await readFile((await download.path())!)
  expect(JSON.parse(data.toString())).toMatchObject({saveVersion:1,contentVersion:'1.0.0',coins:121,day:{number:2,orders:0}})
  await page.locator('#import-file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{"saveVersion":2}')})
  await expect(page.getByText('请用更新版本的游戏打开该存档。')).toBeVisible()
  expect((await saved(page)).coins).toBe(121)
  await dialog(page).getByRole('button',{name:'清空存档',exact:true}).click()
  await expect(dialog(page).getByRole('heading',{name:'确认清空存档'})).toBeVisible()
  await page.keyboard.press('Escape')
  expect((await saved(page)).coins).toBe(121)
  await dialog(page).getByRole('button',{name:'清空存档',exact:true}).click()
  await dialog(page).getByRole('button',{name:'确认清空存档',exact:true}).click()
  await expect(page.getByRole('button',{name:'开始游戏',exact:true})).toBeVisible()
  expect(await saved(page)).toBeNull()
  await page.getByRole('button',{name:'设置',exact:true}).click()
  await page.locator('#import-file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:data})
  await expect(page.locator('.street-canvas')).toBeVisible()
  expect(await saved(page)).toMatchObject({coins:121,day:{number:2},character:{name:'小岚',outfit:2},equipment:1,unlockedStalls:['fried']})
  await page.reload()
  await expect(page.getByRole('button',{name:'继续游戏'})).toBeVisible()
  expect(problems).toEqual([])
})
